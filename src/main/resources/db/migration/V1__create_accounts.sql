CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name VARCHAR(120) NOT NULL,
    balance DECIMAL(19, 2) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

